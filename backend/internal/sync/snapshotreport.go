// SnapshotDiffSource identifies a stored snapshot and hashes its exact data string.
type SnapshotDiffSource struct {
	ID        string `json:"id"`
	FetchedAt string `json:"fetchedAt"`
	SHA256    string `json:"sha256"`
}

// SnapshotDiffProvenance records the sources and author of a generated comparison.
type SnapshotDiffProvenance struct {
	ConnectorID   string             `json:"connectorId"`
	ConnectorName string             `json:"connectorName"`
	From          SnapshotDiffSource `json:"from"`
	To            SnapshotDiffSource `json:"to"`
	GeneratedAt   time.Time          `json:"generatedAt"`
	GeneratedBy   string             `json:"generatedBy"`
}

// SnapshotSourceFromRecord builds provenance from a stored snapshot row.
func SnapshotSourceFromRecord(id, fetchedAt, data string) SnapshotDiffSource {
	hash := sha256.Sum256([]byte(data))
	return SnapshotDiffSource{id, fetchedAt, hex.EncodeToString(hash[:])}
}

func reportValue(v any) string {
	if v == nil {
		return ""
	}
	if s, ok := v.(string); ok {
		return s
	}
	b, err := json.Marshal(v)
	if err != nil {
		return fmt.Sprint(v)
	}
	return string(b)
}

func snapshotReportRows(d SnapshotDiff) [][]string {
	rows := make([][]string, 0, len(d.Sections)+len(d.Entities)+len(d.Dependencies))
	for _, s := range d.Sections {
		for _, p := range s.Patches {
			rows = append(rows, []string{"section", p.Section, "content", s.Type, p.Old, p.New})
		}
	}
	for _, e := range d.Entities {
		rows = append(rows, []string{"entity:" + e.Kind, e.Key, e.Field, e.Change, reportValue(e.Old), reportValue(e.New)})
	}
	for _, dep := range d.Dependencies {
		rows = append(rows, []string{"dependency:" + dep.Kind, dep.Name + ":" + dep.Ref, "dependency", dep.Change, "", ""})
	}
	return rows
}

// safeCSVCell keeps spreadsheet applications from evaluating data as a formula.
func safeCSVCell(value string) string {
	trimmed := strings.TrimLeftFunc(value, unicode.IsSpace)
	if trimmed != "" && strings.ContainsRune("=+-@", rune(trimmed[0])) {
		return "'" + value
	}
	return value
}

// RenderSnapshotDiff returns an export body and content type for a supported format.
func RenderSnapshotDiff(d SnapshotDiff, format string) ([]byte, string, error) {
	switch format {
	case "json":
		b, err := json.MarshalIndent(d, "", "  ")
		return append(b, '\n'), "application/json", err
	case "csv":
		var b bytes.Buffer
		p := d.Provenance
		for _, kv := range [][2]string{{"connectorId", p.ConnectorID}, {"connectorName", p.ConnectorName}, {"fromId", p.From.ID}, {"fromFetchedAt", p.From.FetchedAt}, {"fromSha256", p.From.SHA256}, {"toId", p.To.ID}, {"toFetchedAt", p.To.FetchedAt}, {"toSha256", p.To.SHA256}, {"generatedAt", p.GeneratedAt.UTC().Format(time.RFC3339)}, {"generatedBy", p.GeneratedBy}} {
			fmt.Fprintf(&b, "# %s: %s\n", kv[0], strings.ReplaceAll(strings.ReplaceAll(kv[1], "\r", " "), "\n", " "))
		}
		w := csv.NewWriter(&b)
		if err := w.Write([]string{"kind", "key", "field", "change", "old", "new"}); err != nil {
			return nil, "", err
		}
		rows := snapshotReportRows(d)
		for _, row := range rows {
			for i, cell := range row {
				row[i] = safeCSVCell(cell)
			}
		}
		if err := w.WriteAll(rows); err != nil {
			return nil, "", err
		}
		return b.Bytes(), "text/csv", nil
	case "md":
		return []byte(renderSnapshotMarkdown(d)), "text/markdown", nil
	case "html":
		var b bytes.Buffer
		err := snapshotHTMLTemplate.Execute(&b, struct {
			Diff SnapshotDiff
			Rows [][]string
		}{d, snapshotReportRows(d)})
		return b.Bytes(), "text/html", err
	default:
		return nil, "", fmt.Errorf("unsupported snapshot diff format %q", format)
	}
}

func renderSnapshotMarkdown(d SnapshotDiff) string {
	var b strings.Builder
	p := d.Provenance
	s := d.Summary
	fmt.Fprintf(&b, "# Snapshot diff: %s\n\n", p.ConnectorName)
	fmt.Fprintf(&b, "- Connector ID: %s\n- From: %s (%s)\n- From SHA-256: `%s`\n- To: %s (%s)\n- To SHA-256: `%s`\n- Generated at: %s\n- Generated by: %s\n\n", p.ConnectorID, p.From.ID, p.From.FetchedAt, p.From.SHA256, p.To.ID, p.To.FetchedAt, p.To.SHA256, p.GeneratedAt.UTC().Format(time.RFC3339), p.GeneratedBy)
	fmt.Fprintf(&b, "## Summary\n\nSections: %d added, %d removed, %d modified. Entities: %d added, %d removed, %d modified. Dependencies: %d added, %d removed.\n\n", s.SectionsAdded, s.SectionsRemoved, s.SectionsModified, s.EntitiesAdded, s.EntitiesRemoved, s.EntitiesModified, s.DependenciesAdded, s.DependenciesRemoved)
	fmt.Fprint(&b, "## Sections\n\n")
	for _, section := range d.Sections {
		fmt.Fprintf(&b, "### %s (%s)\n\n", section.Summary, section.Type)
		for _, patch := range section.Patches {
			fmt.Fprintf(&b, "```diff\n%s```\n\n", UnifiedHunks(patch.Old, patch.New))
		}
	}
	fmt.Fprint(&b, "## Entities\n\n")
	for _, e := range d.Entities {
		fmt.Fprintf(&b, "- %s `%s:%s` %s %s: `%s` → `%s`\n", e.Change, e.Kind, e.Key, e.Name, e.Field, reportValue(e.Old), reportValue(e.New))
	}
	fmt.Fprint(&b, "\n## Dependencies\n\n")
	for _, dep := range d.Dependencies {
		fmt.Fprintf(&b, "- %s `%s:%s:%s`\n", dep.Change, dep.Kind, dep.Name, dep.Ref)
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

